def parse_args() -> argparse.Namespace:
    """Parse CLI arguments."""

    parser = argparse.ArgumentParser(
        description="Fit and benchmark an out-of-fold Wiener-plus-ML logistic score fusion.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--scores-npz", type=str, default=str(DEFAULT_SCORES_NPZ))
    parser.add_argument("--report-json", type=str, default=str(DEFAULT_REPORT_JSON))
    parser.add_argument("--output-dir", type=str, default=str(DEFAULT_OUTPUT_DIR))
    parser.add_argument("--wiener-method", type=str, default="wiener_feeney_matched_filter")
    parser.add_argument("--ml-method", type=str, default="imagenet_b64_aux")
    parser.add_argument("--fusion-name", type=str, default="wiener_imagenet_logistic_oof")
    parser.add_argument("--regularization-c", type=float, default=1.0)
    parser.add_argument("--max-iter", type=int, default=1000)
    return parser.parse_args()


def validate_args(args: argparse.Namespace) -> None:
    """Validate required inputs and model settings."""

    for label, path_text in (
        ("--scores-npz", args.scores_npz),
        ("--report-json", args.report_json),
    ):
        path = Path(str(path_text)).expanduser()
        if not path.exists():
            raise FileNotFoundError(f"Missing {label} input: {path}")
    if not str(args.wiener_method).strip():
        raise ValueError("--wiener-method must be non-empty.")
    if not str(args.ml_method).strip():
        raise ValueError("--ml-method must be non-empty.")
    if str(args.wiener_method) == str(args.ml_method):
        raise ValueError("--wiener-method and --ml-method must differ.")
    if not np.isfinite(float(args.regularization_c)) or float(args.regularization_c) <= 0.0:
        raise ValueError("--regularization-c must be finite and positive.")
    if int(args.max_iter) <= 0:
        raise ValueError("--max-iter must be positive.")


def load_json(path: Path) -> dict[str, Any]:
    """Load one JSON object."""

    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def mean_recall(rows: list[dict[str, Any]], method: str) -> float:
    """Return the arithmetic mean cell recall for one method."""

    values = [float(row["p_det"]) for row in rows if str(row["method"]) == str(method)]
    if not values:
        raise ValueError(f"No recall rows for method {method!r}.")
    return float(np.mean(np.asarray(values, dtype=np.float64)))


def cell_map(rows: list[dict[str, Any]], method: str) -> dict[tuple[float, float], dict[str, Any]]:
    """Index recall rows by ``(amplitude, theta_crit_deg)`` for one method."""

    out: dict[tuple[float, float], dict[str, Any]] = {}
    for row in rows:
        if str(row["method"]) != str(method):
            continue
        key = (float(row["amplitude"]), float(row["theta_crit_deg"]))
        out[key] = row
    if not out:
        raise ValueError(f"No recall rows for method {method!r}.")
    return out


def compare_methods(
    rows: list[dict[str, Any]],
    baseline: str,
    challenger: str,
) -> dict[str, Any]:
    """Return head-to-head cell comparison counts and extreme cells."""

    base = cell_map(rows, baseline)
    trial = cell_map(rows, challenger)
    shared = sorted(set(base) & set(trial))
    if not shared:
        raise ValueError(f"No shared recall cells between {baseline!r} and {challenger!r}.")

    raw_better = raw_worse = raw_tied = 0
    ci_better = ci_worse = ci_overlap = 0
    deltas: list[dict[str, Any]] = []
    for key in shared:
        base_row = base[key]
        trial_row = trial[key]
        delta = float(trial_row["p_det"]) - float(base_row["p_det"])
        deltas.append(
            {
                "amplitude": float(key[0]),
                "theta_crit_deg": float(key[1]),
                "baseline_p_det": float(base_row["p_det"]),
                "challenger_p_det": float(trial_row["p_det"]),
                "delta_p_det": delta,
                "baseline_ci95": [float(base_row["ci95_low"]), float(base_row["ci95_high"])],
                "challenger_ci95": [float(trial_row["ci95_low"]), float(trial_row["ci95_high"])],
            }
        )
        if delta > 0.0:
            raw_better += 1
        elif delta < 0.0:
            raw_worse += 1
        else:
            raw_tied += 1

        if float(trial_row["ci95_low"]) > float(base_row["ci95_high"]):
            ci_better += 1
        elif float(trial_row["ci95_high"]) < float(base_row["ci95_low"]):
            ci_worse += 1
        else:
            ci_overlap += 1

    deltas.sort(key=lambda row: float(row["delta_p_det"]))
    return {
        "baseline": baseline,
        "challenger": challenger,
        "num_cells": int(len(shared)),
        "raw_better": int(raw_better),
        "raw_worse": int(raw_worse),
        "raw_tied": int(raw_tied),
        "ci_better": int(ci_better),
        "ci_worse": int(ci_worse),
        "ci_overlap": int(ci_overlap),
        "best_gain_cell": deltas[-1],
        "worst_loss_cell": deltas[0],
    }


def build_fold_ids(manifest: dict[str, Any], source_row_index: np.ndarray) -> np.ndarray:
    """Map each source-row index to its manifest shard id."""

    row_to_fold: dict[int, int] = {}
    for shard in manifest.get("shards", []):
        shard_id = int(shard["shard_id"])
        for row in shard.get("rows", []):
            row_int = int(row)
            if row_int in row_to_fold:
                raise ValueError(f"Source row {row_int} appears in more than one shard.")
            row_to_fold[row_int] = shard_id
    if not row_to_fold:
        raise ValueError("Manifest JSON does not contain shard rows.")

    fold_ids = np.full(source_row_index.shape, -1, dtype=np.int16)
    for idx, row_index in enumerate(np.asarray(source_row_index, dtype=np.int64)):
        if int(row_index) not in row_to_fold:
            raise KeyError(f"Source row {int(row_index)} is missing from manifest shards.")
        fold_ids[idx] = np.int16(row_to_fold[int(row_index)])
    return fold_ids


def fit_oof_logistic(
    features: np.ndarray,
    labels: np.ndarray,
    fold_ids: np.ndarray,
    *,
    regularization_c: float,
    max_iter: int,
) -> tuple[np.ndarray, list[dict[str, Any]]]:
    """Return out-of-fold logistic scores and per-fold diagnostics."""

    if features.ndim != 2 or features.shape[1] != 2:
        raise ValueError(f"Expected a (n, 2) feature matrix; got {features.shape}.")
    if labels.shape[0] != features.shape[0] or fold_ids.shape[0] != features.shape[0]:
        raise ValueError("Feature, label, and fold arrays must have the same length.")
    if not np.all(np.isfinite(features)):
        raise ValueError("Fusion features contain non-finite values.")

    fused = np.full(labels.shape, np.nan, dtype=np.float64)
    diagnostics: list[dict[str, Any]] = []
    for fold_id in sorted(int(value) for value in np.unique(fold_ids)):
        test_mask = np.asarray(fold_ids == fold_id, dtype=bool)
        train_mask = ~test_mask
        if not np.any(test_mask):
            raise ValueError(f"Fold {fold_id} has no held-out rows.")
        if np.count_nonzero(labels[train_mask] == 0) == 0 or np.count_nonzero(labels[train_mask] == 1) == 0:
            raise ValueError(f"Fold {fold_id} training split is missing one class.")

        scaler = StandardScaler()
        x_train = scaler.fit_transform(np.asarray(features[train_mask], dtype=np.float64))
        x_test = scaler.transform(np.asarray(features[test_mask], dtype=np.float64))
        model = LogisticRegression(
            C=float(regularization_c),
            solver="lbfgs",
            max_iter=int(max_iter),
        )
        model.fit(x_train, np.asarray(labels[train_mask], dtype=np.int32))
        fused[test_mask] = model.predict_proba(x_test)[:, 1]
        diagnostics.append(
            {
                "fold_id": int(fold_id),
                "num_train": int(np.count_nonzero(train_mask)),
                "num_test": int(np.count_nonzero(test_mask)),
                "num_train_positive": int(np.count_nonzero(labels[train_mask] == 1)),
                "num_train_negative": int(np.count_nonzero(labels[train_mask] == 0)),
                "coef_scaled": [float(value) for value in model.coef_[0]],
                "intercept_scaled": float(model.intercept_[0]),
                "scaler_mean": [float(value) for value in scaler.mean_],
                "scaler_scale": [float(value) for value in scaler.scale_],
            }
        )
    if not np.all(np.isfinite(fused)):
        raise ValueError("Out-of-fold fusion produced non-finite scores.")
    return fused.astype(np.float32), diagnostics


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    """Write a flat recall CSV."""

    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def write_markdown(path: Path, report: dict[str, Any]) -> None:
    """Write a compact fusion summary."""

    lines = ["# Same-Grid Wiener + ML Fusion", ""]
    lines.append("## Assumptions")
    lines.append("")
    for note in report["assumption_notes"]:
        lines.append(f"- {note}")
    lines.append("")
    lines.append("## Configuration")
    lines.append("")
    lines.append(f"- `wiener_method`: `{report['wiener_method']}`")
    lines.append(f"- `ml_method`: `{report['ml_method']}`")
    lines.append(f"- `fusion_name`: `{report['fusion_name']}`")
    lines.append(f"- `fpr_target`: `{report['fpr_target']}`")
    lines.append(f"- `num_rows`: `{report['num_rows']}`")
    lines.append(f"- `num_folds`: `{report['num_folds']}`")
    lines.append("")
    lines.append("## Mean Recall")
    lines.append("")
    lines.append("| method | mean recall | threshold | realized negative FPR |")
    lines.append("|---|---:|---:|---:|")
    for method in report["methods_order"]:
        row = report["thresholds"][method]
        lines.append(
            f"| {method} | {report['mean_recall'][method]:.4f} | "
            f"{float(row['threshold']):.8g} | {float(row['negative_fpr']):.4f} |"
        )
    lines.append("")
    lines.append("## Head-To-Head")
    lines.append("")
    for label, comparison in report["comparisons"].items():
        lines.append(f"### {label}")
        lines.append("")
        lines.append(
            f"- raw cells: better `{comparison['raw_better']}`, worse `{comparison['raw_worse']}`, tied `{comparison['raw_tied']}`"
        )
        lines.append(
            f"- non-overlapping 95% CI cells: better `{comparison['ci_better']}`, "
            f"worse `{comparison['ci_worse']}`, overlap `{comparison['ci_overlap']}`"
        )
        best = comparison["best_gain_cell"]
        worst = comparison["worst_loss_cell"]
        lines.append(
            f"- best gain: `A={best['amplitude']:.3g}`, `theta={best['theta_crit_deg']:.1f} deg`, "
            f"`{best['baseline_p_det']:.3f} -> {best['challenger_p_det']:.3f}` "
            f"(`{best['delta_p_det']:+.3f}`)"
        )
        lines.append(
            f"- worst loss: `A={worst['amplitude']:.3g}`, `theta={worst['theta_crit_deg']:.1f} deg`, "
            f"`{worst['baseline_p_det']:.3f} -> {worst['challenger_p_det']:.3f}` "
            f"(`{worst['delta_p_det']:+.3f}`)"
        )
        lines.append("")
    lines.append("## Guardrail")
    lines.append("")
    lines.append(
        "- This is an out-of-fold same-grid screening result. It does not by itself promote a deployment branch "
        "or change the real-sky follow-up story."
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    """Run the same-grid fusion benchmark."""

    args = parse_args()
    validate_args(args)

    scores_path = Path(str(args.scores_npz)).expanduser().resolve()
    report_path = Path(str(args.report_json)).expanduser().resolve()
    output_dir = Path(str(args.output_dir)).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    base_report = load_json(report_path)
    manifest_path = Path(str(base_report["manifest_json"])).expanduser().resolve()
    manifest = load_json(manifest_path)
    source_h5 = Path(str(manifest["source_h5"])).expanduser().resolve()

    npz = np.load(scores_path)
    labels = np.asarray(npz["labels"], dtype=np.uint8)
    source_row_index = np.asarray(npz["source_row_index"], dtype=np.int64)
    wiener_key = f"score__{str(args.wiener_method)}"
    ml_key = f"score__{str(args.ml_method)}"
    if wiener_key not in npz or ml_key not in npz:
        raise KeyError(f"Scores NPZ must contain {wiener_key!r} and {ml_key!r}.")
    wiener_scores = np.asarray(npz[wiener_key], dtype=np.float64)
    ml_scores = np.asarray(npz[ml_key], dtype=np.float64)
    if not (labels.shape == source_row_index.shape == wiener_scores.shape == ml_scores.shape):
        raise ValueError("Scores NPZ arrays must share one common shape.")

    rows = read_selected_rows(source_h5, source_row_index)
    if not np.array_equal(np.asarray(rows.row_index, dtype=np.int64), source_row_index):
        raise ValueError("Source rows loaded from HDF5 do not match the scores NPZ order.")

    fold_ids = build_fold_ids(manifest, source_row_index)
    features = np.column_stack([wiener_scores, ml_scores]).astype(np.float64)
    fused_scores, fold_diagnostics = fit_oof_logistic(
        features,
        labels,
        fold_ids,
        regularization_c=float(args.regularization_c),
        max_iter=int(args.max_iter),
    )

    methods = {
        str(args.wiener_method): np.asarray(wiener_scores, dtype=np.float32),
        str(args.ml_method): np.asarray(ml_scores, dtype=np.float32),
        str(args.fusion_name): fused_scores,
    }
    recall_rows, thresholds = summarize_scores(methods, rows, float(base_report["fpr_target"]))

    mean_scores = {name: mean_recall(recall_rows, name) for name in methods}
    comparisons = {
        f"{args.fusion_name} vs {args.wiener_method}": compare_methods(
            recall_rows,
            baseline=str(args.wiener_method),
            challenger=str(args.fusion_name),
        ),
        f"{args.fusion_name} vs {args.ml_method}": compare_methods(
            recall_rows,
            baseline=str(args.ml_method),
            challenger=str(args.fusion_name),
        ),
    }

    fusion_npz_path = output_dir / "same_grid_fusion_scores.npz"
    np.savez_compressed(
        fusion_npz_path,
        labels=labels.astype(np.uint8),
        source_row_index=source_row_index.astype(np.int64),
        **{f"score__{str(args.fusion_name)}": fused_scores.astype(np.float32)},
    )
    recall_csv_path = output_dir / "same_grid_fusion_recall_rows.csv"
    write_csv(recall_csv_path, recall_rows)

    report = {
        "created_utc": dt.datetime.utcnow().replace(microsecond=0).isoformat() + "Z",
        "scores_npz": str(scores_path),
        "report_json": str(report_path),
        "manifest_json": str(manifest_path),
        "source_h5": str(source_h5),
        "fusion_scores_npz": str(fusion_npz_path),
        "fusion_recall_csv": str(recall_csv_path),
        "num_rows": int(labels.size),
        "num_positive": int(np.count_nonzero(labels == 1)),
        "num_negative": int(np.count_nonzero(labels == 0)),
        "num_folds": int(len(np.unique(fold_ids))),
        "fpr_target": float(base_report["fpr_target"]),
        "wiener_method": str(args.wiener_method),
        "ml_method": str(args.ml_method),
        "fusion_name": str(args.fusion_name),
        "methods_order": [str(args.wiener_method), str(args.ml_method), str(args.fusion_name)],
        "thresholds": thresholds,
        "mean_recall": mean_scores,
        "comparisons": comparisons,
        "fold_diagnostics": fold_diagnostics,
        "recall_rows": recall_rows,
        "assumption_notes": [
            "Fusion uses out-of-fold logistic calibration over manifest shards, not an in-sample fit.",
            "Thresholds are matched to the same negative-only target FPR as the base same-grid report.",
            "This is a same-grid screening comparison, not a deployment validation or cosmological evidence statement.",
        ],
    }

    json_path = output_dir / "same_grid_fusion_report.json"
    md_path = output_dir / "same_grid_fusion_report.md"
    json_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_markdown(md_path, report)
    print(
        json.dumps(
            {
                "fusion_name": str(args.fusion_name),
                "mean_recall": mean_scores[str(args.fusion_name)],
                "output_json": str(json_path),
                "output_markdown": str(md_path),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
