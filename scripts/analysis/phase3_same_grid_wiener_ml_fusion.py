"""Benchmark a calibrated Wiener-plus-ML score fusion on the same-grid manifest.

Assumptions
-----------
* The input scores come from the fixed remediated same-grid manifest, so this
  is a screening benchmark on matched injected skies rather than a deployment
  or cosmological-inference result.
* Fusion is evaluated with out-of-fold logistic calibration across manifest
  shards. Each reported fused score is generated by a calibrator that did not
  train on that row.
* The fusion inputs are the true Wiener/Feeney matched-filter score and one ML
  screener score. This tests complementarity, not replacement of the matched
  filter.
* The fused score is thresholded at the same negative-only target FPR used by
  the base same-grid report, so recall comparisons remain on a matched
  screening footing.
"""

